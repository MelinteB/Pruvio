"""Privacy-conscious operational request tracing for Pruvs v7.1.21.

No request path values, bodies, query strings, email, cookies, tokens or headers are
recorded. IDs are generated by the server and are not auth credentials.
"""
from __future__ import annotations
import os
import re
import secrets
from typing import Mapping

_ROUTE = re.compile(r"^/[A-Za-z0-9_{}./-]+$")


def new_request_id() -> str:
    """Independent random correlation ID, not derived from a visitor or session."""
    return secrets.token_hex(12)


def safe_route_template(scope: Mapping) -> str:
    """Only use framework routing templates, never the raw URL or params."""
    route = scope.get('route')
    template = getattr(route, 'path', None)
    if not isinstance(template, str) or len(template) > 120 or not _ROUTE.fullmatch(template):
        return '<unmatched>'
    return template


def slow_threshold_ms(environ: Mapping[str, str] | None = None) -> int:
    environ = os.environ if environ is None else environ
    try:
        number = int(environ.get('PRUVS_SLOW_REQUEST_MS', '1500'))
        if 250 <= number <= 30000:
            return number
    except (ValueError, TypeError, OverflowError):
        pass
    return 1500


def should_log(status: int, elapsed_ms: float, threshold_ms: int) -> bool:
    return status >= 500 or elapsed_ms >= threshold_ms


def safe_method(value: str) -> str:
    value = (value or '').upper()
    return value if value in ('GET', 'HEAD', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS') else 'OTHER'
