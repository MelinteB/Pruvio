-- Pruvs Core: additive social account identities. Run on Core DB only.
-- No existing account is linked automatically by matching email addresses.
BEGIN;
CREATE TABLE IF NOT EXISTS pruvs_social_accounts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    provider VARCHAR(32) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    display_name VARCHAR(255),
    connected_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
    last_used_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT uq_pruvs_social_provider_subject UNIQUE (provider, subject),
    CONSTRAINT uq_pruvs_social_user_provider UNIQUE (user_id, provider)
);
CREATE INDEX IF NOT EXISTS ix_pruvs_social_accounts_user_id
ON pruvs_social_accounts(user_id);
COMMIT;
